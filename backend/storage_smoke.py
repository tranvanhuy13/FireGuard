"""Explicit live storage check; never import the application or send notifications."""
import hashlib
import json
import os
import tempfile
import uuid


def main():
    import requests

    # Importing storage creates its local fallback directory. Isolate that side effect.
    with tempfile.TemporaryDirectory(prefix="fireguard-storage-check-") as folder:
        os.environ["SNAPSHOT_DIR"] = folder
        import storage

        if not storage.S3_ENDPOINT:
            raise RuntimeError("S3_ENDPOINT is required for the live storage check")
        store = storage._get_store()
        key = "snapshots/storage-check-" + uuid.uuid4().hex + ".txt"
        data = ("FireGuard storage verification " + uuid.uuid4().hex).encode()
        try:
            store.put(key, data, "text/plain")
            store.stat(key)
            if store.get(key) != data:
                raise RuntimeError("Storage download did not match uploaded bytes")
            with requests.get(store.snapshot_url(key), timeout=(2, 15)) as response:
                response.raise_for_status()
                if response.content != data:
                    raise RuntimeError("Signed download did not match uploaded bytes")
            print(json.dumps({"storage_check": "passed", "upload": True,
                              "download": True, "signed_download": True,
                              "sha256": hashlib.sha256(data).hexdigest()}), flush=True)
        finally:
            # Only the disposable object generated by this invocation is removed.
            store.delete(key)
        if store.get(key) is not None:
            raise RuntimeError("Storage check object was not removed")
        print('{"storage_cleanup":"passed"}', flush=True)


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:
        # Provider exceptions may include signed URLs or credential identifiers.
        print(json.dumps({"storage_check": "failed", "error_type": type(exc).__name__}), flush=True)
        raise SystemExit(1)
